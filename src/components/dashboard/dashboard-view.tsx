"use client";

import { useRouter } from "next/navigation";
import { useEffect, useRef, useState } from "react";

import { useToast } from "@/components/shell/toast";
import { defaultsFor, type DashboardField, type FieldKind } from "@/lib/dashboard/field";
import { createField, reorderFields, updateDashboard } from "@/server/actions/dashboards";
import type { DashboardDetail } from "@/server/queries/dashboards";

import { AddField } from "./add-field";
import { FieldRow } from "./field-row";
import { useInvalidateDashboards } from "./use-dashboards";

/** A field drawn before its insert has returned, with the count that retires it. */
type PendingField = { countWhenAdded: number; field: DashboardField };

/**
 * One dashboard, as an ordered column of fields.
 *
 * Phase 2a deliberately renders a single column rather than the free-form grid:
 * the field types are the thing that needs validating first, and a layout engine
 * is the part most likely to change once the types have been lived with. The
 * `grid_*` columns are already stored, so that upgrade is a rendering change.
 */
export function DashboardView({ dashboard, now }: { dashboard: DashboardDetail; now: Date }) {
  const router = useRouter();
  const toast = useToast();
  const invalidate = useInvalidateDashboards();
  const [name, setName] = useState(dashboard.name);

  /**
   * The dragged order, held locally while a finger or cursor is down.
   *
   * The list is drawn from this the moment it changes and the write is fired
   * without awaiting, matching how every grid mutation works — a reorder that
   * waited for Supabase would lag a drag by a third of a second.
   */
  const [order, setOrder] = useState<string[] | null>(null);
  const [draggingId, setDraggingId] = useState<string | null>(null);

  /**
   * Fields drawn before the insert has come back.
   *
   * They carry a `pending:` id because the real one is generated by Postgres.
   * `defaultsFor` is the same pure function the action uses to seed the row, so
   * the placeholder is not a guess — it renders exactly what is being written.
   */
  const [adding, setAdding] = useState<PendingField[]>([]);

  const nameInput = useRef<HTMLInputElement>(null);
  useEffect(() => {
    if (document.activeElement !== nameInput.current) setName(dashboard.name);
  }, [dashboard.name]);

  /**
   * The list as drawn: the dragged order if it still describes these fields,
   * otherwise the server's.
   *
   * Derived rather than reconciled in an effect. A local order that has been
   * overtaken — the write landed, or a field was added or removed elsewhere —
   * simply stops matching and the server's order takes over on the next render,
   * with no `setState` in an effect to trigger a cascading one.
   */
  const saved = (() => {
    if (!order) return dashboard.fields;

    const found = order
      .map((id) => dashboard.fields.find((field) => field.id === id))
      .filter((field): field is (typeof dashboard.fields)[number] => field !== undefined);

    return found.length === dashboard.fields.length ? found : dashboard.fields;
  })();

  /**
   * Placeholders still waiting for their real row.
   *
   * Each is recorded with the server count at the moment it was added, so it
   * retires exactly when the list has grown past that — no id matching, since
   * the id is Postgres's to assign. Derived during render rather than reconciled
   * in an effect, which `react-hooks/set-state-in-effect` forbids and which
   * would flash the row twice besides.
   */
  const stillPending = adding.filter((entry) => dashboard.fields.length <= entry.countWhenAdded);

  const fields = [...saved, ...stillPending.map((entry) => entry.field)];

  const handleAdd = (kind: FieldKind) => {
    const { config, value } = defaultsFor(kind);
    const id = `pending:${crypto.randomUUID()}`;
    const entry: PendingField = {
      countWhenAdded: dashboard.fields.length + adding.length,
      field: { id, label: "", kind, config, value } as DashboardField,
    };

    setAdding((current) => [...current, entry]);

    // Fired without awaiting: the row is already on screen, so a round trip
    // between the click and the first sight of it buys nothing.
    //
    // The entry is dropped on both paths. `stillPending` hides it as soon as the
    // refreshed list is long enough, but the array itself has to shrink too, or
    // `countWhenAdded` climbs past the server count and later placeholders stick.
    void createField({ dashboardId: dashboard.id, kind })
      .then(() => {
        invalidate();
        router.refresh();
        setAdding((current) => current.filter((pending) => pending.field.id !== id));
      })
      .catch(() => {
        setAdding((current) => current.filter((pending) => pending.field.id !== id));
        toast("Could not add that field.");
      });
  };

  const startDrag = (id: string, event: React.PointerEvent) => {
    event.preventDefault();
    setDraggingId(id);

    const ids = fields.map((field) => field.id);
    const rows = Array.from(
      event.currentTarget.closest("ul")?.querySelectorAll("li[data-field-id]") ?? [],
    ) as HTMLElement[];

    let next = ids;

    const onMove = (move: PointerEvent) => {
      // Which row the pointer is over, by midpoint — the same "nearest slot"
      // rule the grid uses, and it means no drop targets are needed.
      const target = rows.findIndex((row) => {
        const box = row.getBoundingClientRect();
        return move.clientY < box.top + box.height / 2;
      });

      const from = next.indexOf(id);
      const to = target === -1 ? next.length - 1 : Math.max(0, target);
      if (from === to) return;

      const reordered = [...next];
      reordered.splice(from, 1);
      reordered.splice(to, 0, id);
      next = reordered;
      setOrder(reordered);
    };

    const onUp = () => {
      window.removeEventListener("pointermove", onMove);
      window.removeEventListener("pointerup", onUp);
      window.removeEventListener("pointercancel", onUp);
      setDraggingId(null);

      if (sameOrder(next, ids)) return;

      const previous = ids;
      void reorderFields({ dashboardId: dashboard.id, orderedIds: next })
        .then(invalidate)
        .catch(() => {
          setOrder(previous);
          router.refresh();
          toast("Could not save the new order.");
        });
    };

    window.addEventListener("pointermove", onMove);
    window.addEventListener("pointerup", onUp);
    window.addEventListener("pointercancel", onUp);
  };

  return (
    <div className="mx-auto w-full max-w-2xl px-4 py-6 sm:px-6">
      <input
        ref={nameInput}
        value={name}
        placeholder="Untitled dashboard"
        aria-label="Dashboard name"
        onChange={(event) => setName(event.target.value)}
        onBlur={() => {
          if (name === dashboard.name) return;
          const previous = dashboard.name;
          void updateDashboard({ id: dashboard.id, name })
            .then(invalidate)
            .catch(() => {
              setName(previous);
              router.refresh();
              toast("Could not rename the dashboard.");
            });
        }}
        className="text-ink placeholder:text-ink-faint w-full bg-transparent text-2xl font-semibold tracking-tight outline-none"
      />

      <ul className="mt-5 space-y-2">
        {fields.map((field) => {
          // A row still in flight has no real id yet, so it cannot be reordered
          // or edited — the write would name a row that does not exist.
          const isPending = field.id.startsWith("pending:");

          return (
            <FieldRow
              key={field.id}
              field={field}
              now={now}
              pending={isPending}
              dragging={draggingId === field.id}
              onDragStart={isPending ? undefined : (event) => startDrag(field.id, event)}
            />
          );
        })}
      </ul>

      {/* Not disabled while a row is in flight: each click already draws its own
          row, so several fields can be added without waiting between them. */}
      <div className="mt-3">
        <AddField onPick={handleAdd} />
      </div>

      {fields.length === 0 ? (
        <p className="text-ink-faint mt-6 text-center text-sm">
          Nothing tracked yet. Add a field and pick what kind of thing it is.
        </p>
      ) : null}
    </div>
  );
}

function sameOrder(a: string[], b: string[]): boolean {
  return a.length === b.length && a.every((id, index) => id === b[index]);
}
